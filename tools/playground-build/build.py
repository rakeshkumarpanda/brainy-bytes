"""Pack the Code Playground starter programs into assets/playground/pg-examples.js.

Each language has the same four programs in examples/<lang>/<id>.<ext>. Edit those files, then run
    python3 tools/playground-build/build.py
check.sh runs every example (and the tests in samples/) with the real compilers and with the playground
runner, and shows any difference.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'assets' / 'playground' / 'pg-examples.js'
EXT = {'java': 'java', 'python': 'py', 'c': 'c', 'cpp': 'cpp', 'js': 'js', 'ts': 'ts', 'cs': 'cs'}
EXAMPLES = [
    ('hello', 'Hello and input', 'Asha\n12\n'),
    ('shop', 'Shop bill: a loop and a function', ''),
    ('grades', 'Report card: a class and sorting', ''),
    ('bug', 'Find the bug: read an error', ''),
]

data = {}
for lang, ext in EXT.items():
    data[lang] = [{'id': i, 'title': t, 'stdin': s, 'code': (HERE / 'examples' / lang / f'{i}.{ext}').read_text()} for i, t, s in EXAMPLES]

OUT.write_text('/* Generated by tools/playground-build/build.py from tools/playground-build/examples. Edit those files and run it again. */\n'
               'var PG_EXAMPLES = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
print('wrote', OUT, OUT.stat().st_size, 'bytes')
