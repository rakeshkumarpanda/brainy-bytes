"""Build the SQL chapter pages in content/sql/ from the topic files in topics/.

The pages use the same layout, tabs and checks as the Computer Vision, Git and Cybersecurity subjects
(tools/cv-build/build.py), so this file changes that builder's settings and adds what SQL needs:

  - runnable SQL blocks (K.sql) and hands on labs (K.lab). Every block runs at build time with sql.js 1.16.0
    (tools/sql-build/run.js), the same SQLite the page loads from assets/vendor/sqljs, and its real output is stored
    in the page. A block that fails stops the build unless it is marked err=True, and then it must fail.
    Every lab's model solution must run and return rows, and the page compares the reader's rows with those.
  - playful step animations (pk(...)) from assets/sqlwidgets.js on the shared VIZ player and assets/playkit.js
  - the sample databases in data/*.sql, written to assets/sqldata.js for the playground and the animations
  - one background voice talk per lesson (K.talk), written to data/talk/sql/<slug>.js
  - the Material 3 layer (tools/md3-build/inject.py)

Usage:  python3 tools/sql-build/build.py [--fast] [slug ...]   (--fast skips the cheatsheet)
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'cv-build'))
import build as B  # noqa: E402

sys.path.append(HERE)
sys.path.append(os.path.join(os.path.dirname(HERE), 'md3-build'))
import inject as MD3  # noqa: E402

ROOT = B.ROOT
B.CFG.update({
    'subject': 'sql', 'name': 'SQL and Databases', 'topics': os.path.join(HERE, 'topics'),
    'func': 'sqlModules', 'marker': 'sql-build', 'builder': 'tools/sql-build/build.py', 'badge': 'SQL',
    'widgets': ['cvviz.js', 'viz.js', 'playkit.js', 'vendor/sqljs/sql-wasm.js', 'sqlrun.js', 'sqldata.js', 'sqlplay.js', 'sqlwidgets.js'],
    'css': ['cv.css', 'viz.css', 'playkit.css', 'sql.css'], 'body': 'cvp sqlp',
    'min_calc': 8, 'min_assign': 0, 'fx_word': ('Syntax', 'Syntax', 'syntax card'),
})
MIN_LABS = 3
DATASETS = sorted(f[:-4] for f in os.listdir(os.path.join(HERE, 'data')) if f.endswith('.sql'))


def pk_names():
    src = open(os.path.join(ROOT, 'assets', 'sqlwidgets.js'), encoding='utf-8').read()
    return set(re.findall(r"SQW\('([\w-]+)'", src))


_orig_viz = B.viz_names
B.viz_names = lambda: _orig_viz() | {'pk'}


def datasets():
    return {n: open(os.path.join(HERE, 'data', n + '.sql'), encoding='utf-8').read() for n in DATASETS}


def write_sqldata():
    body = json.dumps(datasets(), ensure_ascii=False, indent=1).replace('</', '<\\/')
    open(os.path.join(ROOT, 'assets', 'sqldata.js'), 'w', encoding='utf-8').write(
        '/* Sample databases for the SQL pages. Generated by tools/sql-build/build.py from tools/sql-build/data/*.sql */\n'
        f'window.SQDATA = {body};\n')


def run_jobs(jobs):
    r = subprocess.run(['node', os.path.join(HERE, 'run.js')], input=json.dumps({'datasets': datasets(), 'jobs': jobs}),
                       capture_output=True, text=True, timeout=300)
    if r.returncode:
        raise SystemExit('sql runner failed:\n' + r.stderr)
    return json.loads(r.stdout)


def sql_checks(T, known):
    bad = []
    html = ''.join(p['html'] for p in T['lessons'])
    for k in set(re.findall(r'data-pk="([\w-]+)"', html)) - known:
        bad.append(f'playful animation {k} is not defined in assets/sqlwidgets.js')
    used = set(re.findall(r'class="sq-run" data-q="([^"]+)"', html))
    for k in set(T['runs']) - used:
        bad.append(f'sql block {k} is written but never shown')
    labs_used = set(re.findall(r'class="sq-lab" data-lab="([^"]+)"', html))
    for l in T['labs']:
        if l['id'] not in labs_used:
            bad.append(f'lab {l["id"]} is written but never shown')
        for k in ('title', 'task', 'hint', 'why'):
            t = B.prose(l[k])
            for ch, label in (('—', 'em dash'), ('–', 'en dash'), (';', 'semicolon')):
                if ch in t:
                    bad.append(f'lab {l["id"]}.{k}: {label}')
    if T.get('kind') != 'revision' and len(T['labs']) < MIN_LABS:
        bad.append(f'only {len(T["labs"])} labs, at least {MIN_LABS} are needed')
    for p in T['lessons']:
        t = T['talks'].get(p['id'])
        if not t:
            bad.append(f'lesson {p["id"]} has no voice talk')
        else:
            n = len(t.split())
            if n < 60:
                bad.append(f'talk {p["id"]} has {n} words, at least 60 are needed')
            if ';' in t or '—' in t or '?' in t:
                bad.append(f'talk {p["id"]}: no semicolons, dashes or questions')
    return bad


def run_topic(T):
    jobs = [{'key': 'q:' + k, 'db': r['db'], 'setup': r['setup'], 'src': r['src']} for k, r in T['runs'].items()]
    jobs += [{'key': 'l:' + l['id'], 'db': l['db'], 'setup': l['setup'], 'src': l['solution']} for l in T['labs']]
    res = run_jobs(jobs)
    errs = []
    for k, r in T['runs'].items():
        out = res['q:' + k]
        failed = [o for o in out if 'error' in o]
        if r['err'] and not (failed and out[-1] is failed[0]):
            errs.append(f'sql block {k} is marked err=True but its last statement did not fail')
        if not r['err'] and failed:
            errs.append(f'sql block {k} failed: {failed[0]["error"]} in {failed[0]["sql"][:80]}')
        r['out'] = out
    for l in T['labs']:
        out = res['l:' + l['id']]
        if any('error' in o for o in out) or not out or not out[-1]['cols']:
            errs.append(f'lab {l["id"]}: the model solution must run and end with a query: {out[-1] if out else "nothing"}')
        else:
            l['want'] = {'cols': out[-1]['cols'], 'rows': out[-1]['rows']}
            if not out[-1]['rows']:
                errs.append(f'lab {l["id"]}: the model solution returns no rows')
    if errs:
        raise SystemExit(T['slug'] + ':\n  ' + '\n  '.join(errs))


def write_talks(T):
    d = os.path.join(ROOT, 'data', 'talk', 'sql')
    os.makedirs(d, exist_ok=True)
    body = json.dumps(T['talks'], ensure_ascii=False, indent=1)
    open(os.path.join(d, T['slug'] + '.js'), 'w', encoding='utf-8').write(
        f"/* Background voice talks for content/sql/{T['slug']}.html, read by assets/voiceteach.js (see data/talk/README.md). "
        f"Generated by tools/sql-build/build.py from the topic file. */\nVT_TALK({json.dumps('sql/' + T['slug'])}, {body});\n")


_orig_page = B.page


def page(T, chs, x):
    _orig_page(T, chs, x)
    dest = os.path.join(B.out_dir(), T['slug'] + '.html')
    s = open(dest, encoding='utf-8').read()
    data = {'runs': {k: {kk: v for kk, v in r.items() if kk != 'err'} for k, r in T['runs'].items()},
            'labs': [{k: v for k, v in l.items() if k != 'solution'} | {'solution': l['solution']} for l in T['labs']]}
    tag = f'<script type="application/json" id="sqdata">{B.js(data)}</script>\n'
    s = s.replace('<script src="../../assets/fun.js"></script>', tag + '<script src="../../assets/fun.js"></script>', 1)
    extra = (f'<span class="cv-chip">{len(T["runs"])} runnable {"query" if len(T["runs"]) == 1 else "queries"}</span>' if T['runs'] else '') + \
        (f'<span class="cv-chip">{len(T["labs"])} SQL {"lab" if len(T["labs"]) == 1 else "labs"}</span>' if T['labs'] else '')
    s = s.replace('<a class="cv-chip cv-sheet"', extra + '<a class="cv-chip cv-sheet"', 1)
    open(dest, 'w', encoding='utf-8').write(s)
    MD3.process(dest)
    write_talks(T)


B.page = page

_orig_build = B.build


def build(want):
    known = pk_names()
    chs = B.chapters()
    errs = []
    for T in chs:
        e = sql_checks(T, known)
        if e:
            errs.append(f'{T["slug"]}:\n  ' + '\n  '.join(e))
    if errs:
        raise SystemExit('\n'.join(errs))
    for T in chs:
        if not want or T['slug'] in want:
            run_topic(T)
    write_sqldata()
    # B.build loads the chapters again, so carry the run results over by slug
    done = {T['slug']: T for T in chs}
    real_chapters = B.chapters

    def chapters_again():
        out = real_chapters()
        for T in out:
            if T['slug'] in done:
                T['runs'], T['labs'] = done[T['slug']]['runs'], done[T['slug']]['labs']
        return out
    B.chapters = chapters_again
    try:
        return _orig_build(want)
    finally:
        B.chapters = real_chapters


if __name__ == '__main__':
    fast = '--fast' in sys.argv
    chs = build([a for a in sys.argv[1:] if a != '--fast'])
    if not fast:
        import cheatsheet
        cheatsheet.write(chs, B.CFG, ROOT)
