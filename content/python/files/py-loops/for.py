# 2.2 Loops: while, for, range, break and continue
# Example "for" from the lesson.
# From the Brainy Bytes Python subject. Run it with: python3 <this file>

for fruit in ["apple", "mango", "banana"]:
    print("I like", fruit)

for letter in "Hi!":
    print(letter)

for i in range(3):          # 0, 1, 2
    print("range gives", i)
