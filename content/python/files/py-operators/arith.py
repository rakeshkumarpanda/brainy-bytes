# 1.3 Operators, expressions and the order Python works them out
# Example "arith" from the lesson.
# From the Brainy Bytes Python subject. Run it with: python3 <this file>

a, b = 17, 5
print("a + b  =", a + b)
print("a - b  =", a - b)
print("a * b  =", a * b)
print("a / b  =", a / b)     # true division: always a float
print("a // b =", a // b)    # floor division: round down
print("a % b  =", a % b)     # remainder
print("a ** b =", a ** b)    # power
print("divmod =", divmod(a, b))   # (quotient, remainder) together
